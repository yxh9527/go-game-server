import test from 'node:test';
import assert from 'node:assert/strict';
import {seatFinanceAuthority} from '../../fixtures/seat-finance-authority.js';
import {loadGames} from '../../../game-server/src/games/catalog.js';
import {seedRooms} from '../../../cache/rpc/seed.js';
import {createRegistry} from '../../../game-server/src/registry.js';
import {createAuthoritativeWallet} from '../../../game-server/src/wallet/authoritative.js';
import {createRoundFinance,moneyToScore} from '../../../game-server/src/wallet/round-finance.js';
import {createGameRouteIndex} from '../../../shared/rpc/game-routes.js';
import * as bankers from '../../../game-server/src/core/hundred-banker.js';
import {installUserCenter} from '../../../game-server/src/core/user-center.js';

const games=await loadGames('banker-finance-test'),configs=seedRooms();
for(const type of [58,59])test(type+': real engine bankroll is reserved, bettors and banker settle together, down-bank releases collateral once',async()=>{
 const game=games.byRoomType.get(type),cfg={...configs.find(r=>Number(r.room_type)===type&&Number(r.play_mode||0)===0),finance_level:1};
 const table=game.createTable(Number(cfg.game_room_config_id)*10000,type,cfg);table.agentId=7;
 const authority=seatFinanceAuthority(),registry=createRegistry(),wallet=createAuthoritativeWallet({common:authority.common});
 const runtime={env:'prod',registry,wallet,config:{finance:{banker_net:true}},log:{error(){}}};registry.setTable(table.roomId,table,7,game.id);
 wallet.configureLottery(createRoundFinance(authority.common,{routes:createGameRouteIndex([{gameType:cfg.game_type,roomType:type,number:92000+type,symbol:'bank-'+type,state:1,isFrozen:0}])}),[type],runtime);
 installUserCenter(runtime);
 const sessions=new Map(),messages=[];
 for(const uid of [42,43]){authority.add(uid,1000000);const session={userId:uid,agentId:7,currency:'CNY',authenticated:true,roomId:table.roomId,gameId:game.id};registry.bind({},session);sessions.set(uid,session);await wallet.load(session);}
 const send=(id,payload)=>wallet.deliver(()=>messages.push({id,payload:structuredClone(payload)}));
 const io={env:'prod',wallet,broadcast:send,send:(_ws,id,data)=>send(id,data),sendUser:(_uid,id,data)=>send(id,data),sessionFor:uid=>sessions.get(uid),forEachPlayer:fn=>sessions.forEach(fn)};
 const run=fn=>wallet.run(fn,runtime),ctx=uid=>({table,session:sessions.get(uid),io,wallet,runtime,send});
 await run(()=>game.engine.applyCycle(io,table,0));
 for(const bankerType of [1,2])await run(()=>bankers.request(ctx(42),6133,{roomId:table.roomId,bankerType,amount:20000,maxWinLoseAmount:10000},game.config.bankerAreas));
 await run(()=>bankers.boundary(ctx(42),game.config.bankerAreas));
 assert.equal(sessions.get(42).wallet,1000000);assert.equal(authority.account(42).carry.amount,40000);assert.equal(wallet.available(sessions.get(42)),960000);
 table.state=2;table.phaseEndsAt=Date.now()+60000;
 const areas=game.betOptions(table).areas,area=areas.find(a=>a.areaId===1),amount=game.betOptions(table).minBet;
 await run(()=>game.placeBet(ctx(43),{roomId:table.roomId,roomType:type,params:[{areaId:area.areaId,total:amount}]}));
 assert.equal(sessions.get(43).wallet,1000000-amount);
 await run(()=>game.engine.applyCycle(io,table,3));
 assert.ok(authority.calls.filter(c=>c.method==='bet').some(c=>c.request.items.some(item=>item.userId===42&&item.amount==='0.00'&&item.areaId==='banker:20000')));
 await run(()=>game.engine.applyCycle(io,table,4));
 assert.equal(authority.calls.filter(c=>c.method==='prePay').at(-1).request.items.length,2);
 await run(()=>game.engine.applyCycle(io,table,6));
 const settled=authority.calls.filter(c=>c.method==='settlement');assert.equal(settled.length,1);assert.equal(settled[0].request.mode,'BANKER_NET');
 const bankerItem=settled[0].request.items.find(item=>item.userId===42),net=bankerItem.netScore.startsWith('-')?-moneyToScore(bankerItem.netScore.slice(1)):moneyToScore(bankerItem.netScore);
 assert.equal(authority.account(42).balance,1000000+net);assert.equal(authority.account(42).carry.amount,40000+net);
 assert.equal(table.hundredBankers.entries.reduce((n,e)=>n+e.amount,0),authority.account(42).carry.amount);
 await run(()=>game.engine.applyCycle(io,table,6));assert.equal(authority.calls.filter(c=>c.method==='settlement').length,1);
 const before=sessions.get(42).wallet;
 for(const bankerType of [1,2])await run(()=>bankers.request(ctx(42),6134,{roomId:table.roomId,bankerType},game.config.bankerAreas));
 await run(()=>game.engine.applyCycle(io,table,8));await run(()=>bankers.boundary(ctx(42),game.config.bankerAreas));
 assert.equal(authority.account(42).carry,null);assert.equal(sessions.get(42).wallet,before);assert.equal(table.hundredBankers.entries.length,0);
 assert.equal(table.hundredBankers.collaterals.size,0);
 assert.ok(authority.cashCalls.every(c=>c.steps.every(step=>['reserve','release','renew'].includes(step.kind))));
});

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import yaml from "js-yaml";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const services = ["hall", "client-web", "game-server", "match"];
const excluded = new Set(["test", "tests", "__tests__", "cache", "node_modules", ".git", ".codex", ".agents", "mock-server", "logs"]);
export function isProductionPath(relative) {
  const parts = relative.split(/[\\/]/);
  return !parts.some(part => excluded.has(part) || part.startsWith(".tmp"))
    && !/\.(test|spec)\.[cm]?js$/.test(parts.at(-1))
    && !/\.log$/.test(parts.at(-1));
}

export async function buildProduction({ outputDir = path.join(root, "dist/production"), includeStatic = true } = {}) {
  const destination = path.resolve(outputDir);
  const dist = path.join(root, "dist");
  const relative = path.relative(dist, destination);
  if (!relative || relative.startsWith("..") || path.isAbsolute(relative)) {
    throw new Error("Build output must be a child of this repository's dist directory");
  }
  await fs.mkdir(dist, { recursive: true });
  const realDist = await fs.realpath(dist);
  if (realDist.toLowerCase() !== dist.toLowerCase()) throw new Error("dist must not be a symlink");
  if (path.dirname(destination) !== dist) throw new Error("Build output must be directly inside dist");
  const existing = await fs.lstat(destination).catch(error => { if (error.code !== "ENOENT") throw error; return null; });
  if (existing) {
    if (!existing.isDirectory() || existing.isSymbolicLink()) throw new Error("Build output is not a regular directory");
    const marker = JSON.parse(await fs.readFile(path.join(destination, "build-manifest.json"), "utf8"));
    if (marker.generator !== "gogame-build-prod") throw new Error("Refusing to replace a directory not generated by this builder");
    await fs.rm(destination, { recursive: true, force: true });
  }
  await fs.mkdir(destination);
  const manifest = { generator: "gogame-build-prod", environment: "prod", includesStatic: includeStatic, files: [] };
  const write = async (file, content) => {
    await fs.mkdir(path.dirname(path.join(destination, file)), { recursive: true });
    await fs.writeFile(path.join(destination, file), content);
    manifest.files.push(file);
  };
  async function copy(relativePath) {
    if (!isProductionPath(relativePath)) return;
    const source = path.join(root, relativePath);
    const stat = await fs.lstat(source);
    if (stat.isSymbolicLink()) throw new Error("Unexpected symlink in production input: " + relativePath);
    if (stat.isDirectory()) {
      for (const item of await fs.readdir(source)) await copy(relativePath + "/" + item);
    } else if (stat.isFile()) {
      await fs.mkdir(path.dirname(path.join(destination, relativePath)), { recursive: true });
      await fs.copyFile(source, path.join(destination, relativePath));
      manifest.files.push(relativePath);
    }
  }
  for (const service of services) {
    await copy(service + "/src");
    const pkg = JSON.parse(await fs.readFile(path.join(root, service, "package.json"), "utf8"));
    pkg.scripts = { start: "node ../scripts/prod.js " + service };
    await write(service + "/package.json", JSON.stringify(pkg, null, 2) + "\n");
    if (service !== "client-web") {
      const config = yaml.load(await fs.readFile(path.join(root, service, "config.yaml"), "utf8"));
      config.env = "prod";
      if (config.wallet) { config.wallet.mode = "online"; delete config.wallet.local_balance; }
      await write(service + "/config.yaml", yaml.dump(config));
    }
  }
  await copy("shared");
  await copy("scripts/prod.js");
  if (includeStatic) await copy("static");
  const pkg = JSON.parse(await fs.readFile(path.join(root, "package.json"), "utf8"));
  pkg.scripts = Object.fromEntries(services.map(service => [service, "node scripts/prod.js " + service]));
  pkg.workspaces = services;
  delete pkg.devDependencies;
  delete pkg.files;
  await write("package.json", JSON.stringify(pkg, null, 2) + "\n");
  await copy("package-lock.json");
  await write("DEPLOY.md", "# Production bundle\n\nInstall dependencies with npm ci --omit=dev. Configure the service YAML files for production, then run npm run hall, npm run game-server, npm run match, and npm run client-web under your process manager.\n\nAll production database access is delegated to gogames data-center. Configure data_center and data_center_token (or GOGAME_DATA_CENTER_TOKEN); the data-center service must use the same token. Node services do not require MySQL connection settings. Deploy the matching GogameStorageService protocol, Go implementation and schema changes before enabling these Node adapters. Overlay tests alone do not apply the data-center changes or migrate the database. Authoritative payment integration must be verified separately.\n\nThe launchers force GOGAME_ENV=prod and IS_DEV=0. test/ and cache/ are intentionally absent. Existing runtime room/ranking state and production Redis caching remain in the service code.\n");
  manifest.files.sort();
  await fs.writeFile(path.join(destination, "build-manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
  return { directory: destination, files: manifest.files.length, includesStatic: includeStatic };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(JSON.stringify(await buildProduction(), null, 2));
}
